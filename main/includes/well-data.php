// Merge in wells registered via the admin Site Registration form.
// Import tooling can opt out so its normalized source is not overwritten by
// an older copy of the same records already stored in the database.
if (!($skipDatabaseWellMerge ?? false)) {
require_once __DIR__ . '/../../database/db.php';

try {
    $pdo = idepDatabase();
    $dbWells = $pdo->query("
        SELECT
            w.well_code,
            w.well_name,
            w.latitude,
            w.longitude,
            w.well_depth,
            w.well_type,
            w.absorption_capacity,
            w.address,
            w.photo_path,
            w.installer_name,
            w.installation_date,
            COALESCE(v.name, '—') AS village_name,
            COALESCE(dc.name, '—') AS city_name,
            s.id_device AS sensor_device_id,
            latest.h1 AS latest_h1,
            latest.h2 AS latest_h2,
            latest.hasil AS latest_hasil,
            latest.received_at AS latest_received_at,
            reading_span.first_received_at,
            reading_span.last_received_at,
            reading_span.reading_count,
            reading_span.total_absorption
        FROM wells w
        LEFT JOIN village v ON v.id = w.village_id
        LEFT JOIN sub_district sd ON sd.id = v.sub_district_id
        LEFT JOIN district_city dc ON dc.id = sd.district_id
        LEFT JOIN sensors s ON s.id = w.sensor_id
        LEFT JOIN sensor_readings latest ON latest.id = (
            SELECT sr.id
            FROM sensor_readings sr
            WHERE sr.sensor_id = s.id
            ORDER BY sr.received_at DESC, sr.id DESC
            LIMIT 1
        )
        LEFT JOIN (
            SELECT
                sensor_id,
                MIN(received_at) AS first_received_at,
                MAX(received_at) AS last_received_at,
                COUNT(*) AS reading_count,
                SUM(
                    CASE
                        WHEN COALESCE(h1, 0) = 0 AND COALESCE(h2, 0) = 0 THEN 0
                        WHEN COALESCE(hasil, 0) > 0 THEN hasil
                        ELSE 0
                    END
                ) AS total_absorption
            FROM sensor_readings
            GROUP BY sensor_id
        ) reading_span ON reading_span.sensor_id = s.id
        ORDER BY w.id DESC
    ")->fetchAll();
} catch (Throwable $e) {
    error_log('Well merge query failed: ' . $e->getMessage());
    $dbWells = [];
}

foreach ($dbWells as $row) {
    $firstReadingAt = $row['first_received_at'] ?: null;
    $lastReadingAt = $row['last_received_at'] ?: null;
    $firstReadingDateIso = $firstReadingAt !== null ? substr((string)$firstReadingAt, 0, 10) : null;
    $lastReadingDateIso = $lastReadingAt !== null ? substr((string)$lastReadingAt, 0, 10) : null;
    $readingCount = (int)($row['reading_count'] ?? 0);
    $totalAbsorption = max(0, (float)($row['total_absorption'] ?? 0));
    $totalAbsorptionLabel = $readingCount > 0
        ? number_format($totalAbsorption, 2, '.', ',') . ' L'
        : '—';
    $installDateIso = $row['installation_date'] ?: $firstReadingDateIso;
    $installDateDisplay = $installDateIso
        ? date('d F Y', strtotime($installDateIso))
        : '—';

    $hasCoords = $row['latitude'] !== null && $row['longitude'] !== null;
    $cityName = preg_replace('/^(KAB\.|KOTA)\s+/i', '', (string)$row['city_name']) ?? (string)$row['city_name'];
    $cityName = ucwords(strtolower($cityName));
    if ($row['well_code'] === 'RCH-082') {
        $cityName = ucwords(strtolower((string)$row['village_name']));
    }
    $absorption = trim((string)($row['absorption_capacity'] ?? ''));
    $litresMinute = '—';
    $litresHour = '—';
    if (preg_match('/\d+(?:[.,]\d+)?/', $absorption, $capacityMatch) === 1) {
        $cubicMetresPerHour = (float)str_replace(',', '.', $capacityMatch[0]);
        $litresMinute = number_format($cubicMetresPerHour * 1000 / 60, 1) . ' L/min';
        $litresHour = number_format($cubicMetresPerHour * 1000, 0) . ' L/hour';
    }

    $sensorDeviceId = $row['sensor_device_id'] ?: null;
    $latestReceivedAt = $row['latest_received_at'] ?: null;
    $sensorStatus = 'no-signal';
    $sensorStatusLabel = 'No Signal';
    if ($sensorDeviceId !== null && $latestReceivedAt !== null) {
        $receivedAt = DateTimeImmutable::createFromFormat(
            'Y-m-d H:i:s',
            $latestReceivedAt,
            new DateTimeZone('Asia/Makassar')
        );
        $now = new DateTimeImmutable('now', new DateTimeZone('Asia/Makassar'));
        if ($receivedAt !== false && ($now->getTimestamp() - $receivedAt->getTimestamp()) <= 180) {
            $sensorStatus = 'online';
            $sensorStatusLabel = 'Online';
        }
    }

    $databaseWell = [
        'id' => $row['well_code'],
        'deviceId' => $sensorDeviceId,
        'name' => $row['well_name'],
        'city' => $cityName,
        'lat' => $hasCoords ? (float)$row['latitude'] : null,
        'lng' => $hasCoords ? (float)$row['longitude'] : null,
        'status' => $sensorStatus,
        'statusLabel' => $sensorStatusLabel,
        'startDate' => $installDateDisplay,
        'startDateISO' => $installDateIso,
        'readingStartISO' => $firstReadingDateIso,
        'readingEndISO' => $lastReadingDateIso,
        'totalAbsorptionValue' => round($totalAbsorption, 2),
        'totalAbsorptionLabel' => $totalAbsorptionLabel,
        'endDate' => '—',
        'endDateISO' => null,
        'duration' => 'Ongoing',
        'absorption' => $absorption !== '' ? $absorption : '—',
        'transmission' => $sensorStatus === 'online' ? 'Live' : 'No Signal',
        'lastTransmission' => $latestReceivedAt !== null ? $latestReceivedAt . ' WITA' : '—',
        'wellType' => $row['well_type'] ?: 'Registered Well',
        'litresMinute' => $litresMinute,
        'litresHour' => $litresHour,
        'volume' => '—',
        'inflow' => $absorption !== '' ? $absorption : '—',
        'depth' => $row['well_depth'] !== null ? $row['well_depth'] . ' meters' : '—',
        'address' => $row['address'] ?: $cityName,
        'photo' => $row['photo_path'] ?: $wellPhoto,
        'locationPending' => !$hasCoords,
        'h1' => $row['latest_h1'] ?? '—',
        'h2' => $row['latest_h2'] ?? '—',
        'hasil' => $row['latest_hasil'] ?? '—',
    ];

    $existingIndex = array_search($row['well_code'], array_column($wells, 'id'), true);
    if ($existingIndex !== false) {
        $wells[$existingIndex] = $databaseWell;
    } else {
        $wells[] = $databaseWell;
    }
}
